const UNIVERSITY_ALIASES = {
  UAIC: ["UAIC"],
  UMF: ["UMF"],
  TUIASI: ["TUIASI", "TUIAȘI"],
  USV: ["USV", "USV Iași"],
  UNIVERSITY_OF_ARTS: ["UNIVERSITY_OF_ARTS", "Universitatea de Arte Iași"],
  UPA: [
    "UPA",
    "Universitatea Petre Andrei Iași",
    "Petre Andrei University of Iași (UPA)",
  ],
};

const PROGRAM_LEVEL_LABELS = {
  bachelor: "Bachelor",
  master: "Master",
  doctorate: "Doctorate",
};

export function normalizeUniversityId(universityId) {
  if (!universityId) return "";
  const normalizedInput = String(universityId).trim();
  const matchedEntry = Object.entries(UNIVERSITY_ALIASES).find(([, aliases]) =>
    aliases.some(
      (alias) => alias.toLowerCase() === normalizedInput.toLowerCase(),
    ),
  );
  return matchedEntry ? matchedEntry[0] : normalizedInput;
}

export function getFacultiesByUniversity(universityId) {
  if (!universityId) return IASI_FACULTIES;
  const normalizedRequested = normalizeUniversityId(universityId);
  return IASI_FACULTIES.filter(
    (f) => normalizeUniversityId(f.university) === normalizedRequested,
  );
}

export function getProgramsByFaculty(facultyId) {
  const faculty = IASI_FACULTIES.find((f) => f.id === facultyId);
  if (!faculty) return [];

  const programs = faculty.programs;
  if (Array.isArray(programs)) {
    return programs;
  }
  if (!programs || typeof programs !== "object") {
    return [];
  }

  return Object.values(programs).filter(Array.isArray).flat();
}

export function getProgramOptionsByFaculty(facultyId) {
  const faculty = IASI_FACULTIES.find((f) => f.id === facultyId);
  if (!faculty) return [];

  const programs = faculty.programs;
  if (Array.isArray(programs)) {
    return programs.map((name) => ({
      name,
      level: "",
      label: name,
    }));
  }
  if (!programs || typeof programs !== "object") {
    return [];
  }

  return Object.entries(programs)
    .filter(([, list]) => Array.isArray(list))
    .flatMap(([level, list]) => {
      const levelLabel = PROGRAM_LEVEL_LABELS[level] || level;
      return list.map((name) => ({
        name,
        level,
        label: levelLabel ? `${name} (${levelLabel})` : name,
      }));
    });
}

export function getFacultyById(facultyId) {
  return IASI_FACULTIES.find((f) => f.id === facultyId) || null;
}
