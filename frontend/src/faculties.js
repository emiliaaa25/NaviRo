export function getFacultiesByUniversity(universityId) {
  if (!universityId) return IASI_FACULTIES;
  return IASI_FACULTIES.filter((f) => f.university === universityId);
}

export function getProgramsByFaculty(facultyId) {
  const faculty = IASI_FACULTIES.find((f) => f.id === facultyId);
  return faculty ? faculty.programs : [];
}

export function getFacultyById(facultyId) {
  return IASI_FACULTIES.find((f) => f.id === facultyId) || null;
}
